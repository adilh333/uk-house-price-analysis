def test_every_observed_county_maps_to_a_known_region():
    assert len(OBSERVED_COUNTIES) == 113
    missing = [county for county in OBSERVED_COUNTIES if county_to_region(county) not in REGIONS]
    assert missing == []
    assert known_counties() == set(OBSERVED_COUNTIES)


def test_county_lookup_is_case_insensitive_and_rejects_unknown_names():
    assert county_to_region(" greater   london ") == "London"
    assert county_to_region("cardiff") == "Wales"
    assert county_to_region("ATLANTIS") is None
    assert county_to_region("") is None
    assert county_to_region(None) is None
